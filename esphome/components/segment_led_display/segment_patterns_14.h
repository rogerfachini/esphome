// 14-Segment Display Layout (Starburst/Alphanumeric):
//
//      A1   A2
//     ---- ----
//    |\   |   /|
//  F | H  J  K | B
//    |  \ | /  |
//     ---- ----
//      G1   G2
//     ---- ----
//    |  / | \  |
//  E | L  M  N | C
//    |/   |   \|
//     ---- ----
//      D1   D2
//
// Segment descriptions:
//   A1, A2: Top horizontal (split)
//   B: Upper right vertical
//   C: Lower right vertical
//   D1, D2: Bottom horizontal (split)
//   E: Lower left vertical
//   F: Upper left vertical
//   G1, G2: Middle horizontal (split)
//   H: Upper left diagonal
//   J: Upper center vertical
//   K: Upper right diagonal
//   L: Lower left diagonal
//   M: Lower center vertical
//   N: Lower right diagonal (uses K bit)
//
// Bit mapping (LSB first): A1(0) A2(1) B(2) C(3) D1(4) D2(5) E(6) F(7) G1(8) G2(9) H(10) J(11) K(12) M(13)

