// 16-Segment Display Layout (Full Starburst/Complete Alphanumeric):
//
//      A1   A2
//     ---- ----
//    |\   |   /|
//  F | H  J  K | B
//    |  \ | /  |
//     ---- ----
//      G1   G2
//     ---- ----
//    |  / | \  |
//  E | L  M  N | C
//    |/   |   \|
//     ---- ----
//      D1   D2
//
// Segment descriptions:
//   A1, A2: Top horizontal (split left/right)
//   B: Upper right vertical
//   C: Lower right vertical
//   D1, D2: Bottom horizontal (split left/right)
//   E: Lower left vertical
//   F: Upper left vertical
//   G1, G2: Middle horizontal (split left/right)
//   H: Upper left diagonal (top-left to center)
//   J: Upper center vertical (top to center)
//   K: Upper right diagonal (top-right to center)
//   L: Lower left diagonal (center to bottom-left)
//   M: Lower center vertical (center to bottom)
//   N: Lower right diagonal (center to bottom-right)
//
// Bit mapping (LSB first): A1(0) A2(1) B(2) C(3) D1(4) D2(5) E(6) F(7) G1(8) G2(9) H(10) J(11) K(12) L(13) M(14) N(15)
//
// This configuration allows rendering of full uppercase/lowercase alphabets,
// numbers, and many symbols with high clarity.
