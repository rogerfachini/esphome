// 9-Segment Display Layout (7-segment + 2 diagonals):
//
//        A
//       ---
//      /   \
//  F  / I   \ B
//    |   G   |
//  E  \ J   / C
//      \   /
//       ---
//        D
//
// Segment descriptions:
//   A: Top horizontal
//   B: Upper right vertical
//   C: Lower right vertical
//   D: Bottom horizontal
//   E: Lower left vertical
//   F: Upper left vertical
//   G: Middle horizontal
//   I: Upper diagonal (top-left to center-right)
//   J: Lower diagonal (center-left to bottom-right)
//
// The two diagonal segments (I and J) enable better rendering of
// letters like K, M, N, V, W, X, Y, Z compared to standard 7-segment.
//
// Bit mapping (LSB first): A(0) B(1) C(2) D(3) E(4) F(5) G(6) I(7) J(8)

